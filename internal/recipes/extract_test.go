/*
Reading the crafting book out of a game that is not there.

The book is bundled and regenerated by hand, so this runs perhaps once a
release -- which is exactly why it is worth comparing: a walk that quietly
stopped reading a field would produce a book that looks complete and is missing
something, and nobody would look at it again for months.
*/

const (
	base = 0x10000000
	size = 0x80000

	// get_LocalPlayer and the static the base is derived from. Main.player sits
	// at its own offset inside Main's block, because that is how the base is
	// worked out: the resolver finds this address and subtracts the offset.
	code           = base + 0x1000
	staticAt       = base + 0x10000
	playerStatic   = staticAt + layout.MainPlayerOff
	myPlayerStatic = playerStatic + 4
	playerArray    = base + 0x200

	// The recipe array, the recipe objects, and the item objects they point at.
	recipeArr     = base + 0x20000
	recipeObjects = base + 0x21000
	recipeStride  = 0x40
	itemObjects   = base + 0x14000
	itemArrays    = base + 0x15000
	itemStride    = 0x100
	// The ingredient objects, spread far enough apart that a recipe with more
	// of them than the game reads still fits.
	ingObjects   = base + 0x40000
	ingPerRecipe = 64

	/*
		The station-name lookup: the two instructions that load the statics, the
		statics themselves, and what they point at.

		The names come from the game's own tile display names, which are reached
		through two arrays nothing else in the project touches -- so each static
		is found by matching the code that reads it, and that code has to be here
		for any of it to be exercised.
	*/
	tileCodeAt    = base + 0x2000
	legendCodeAt  = base + 0x2100
	lookupStatic  = base + 0x2200
	legendStatic  = base + 0x2204
	lookupArr     = base + 0x30000
	legendArr     = base + 0x31000
	legendText    = base + 0x32000
	stationNameAt = base + 0x32100

	// Which map-legend entry the workbench tile points at, and what it says.
	benchTile   = 18
	benchLegend = 5
	benchName   = "Work Bench"
)

// recipe is one entry the fixture plants.
type recipeImage struct {
	out   int32
	stack int32
	// ing is [item, count] pairs.
	ing [][2]int32
	// tile is the station, or -1 for something made by hand.
	tile int32
	// planted says to write an output item even when its type is zero, which is
	// how the game's own unused slots read.
	planted bool
	// createTile is what the output places, or -1 if it places nothing.
	createTile int32
	placeStyle int32
}

/*
book is the fixture's recipes.

One made by hand and two at a station, so both branches are walked; an output
that places a tile, because that is the table nothing else would notice being
dropped; and an empty slot in the middle, which the game's own array is full of.
*/
var book = []recipeImage{
	{out: 8, stack: 3, ing: [][2]int32{{23, 1}, {9, 1}}, tile: -1, createTile: -1},
	{out: 24, stack: 1, ing: [][2]int32{{9, 7}}, tile: benchTile, createTile: -1},
	{}, // an unused slot: no object behind it at all
	// A slot with an output item whose type is zero, which is what most of the
	// game's own array looks like.
	{out: 0, stack: 1, tile: -1, createTile: -1, planted: true},
	{out: 35, stack: 1, ing: [][2]int32{{22, 5}}, tile: benchTile, createTile: 16, placeStyle: 2},
	// A recipe with no stack written, and more ingredients than the game reads.
	{out: 71, stack: 0, ing: manyIngredients(45), tile: -1, createTile: -1},
}

// manyIngredients is a recipe that takes more than the walk will look at.
func manyIngredients(n int) [][2]int32 {
	out := make([][2]int32, n)
	for i := range out {
		out[i] = [2]int32{int32(100 + i), int32(i + 1)} //nolint:gosec // a small index
	}
	return out
}

// execMem is a fake whose whole buffer is also code, so the two statics the
// station names need can be found in it.
type execMem struct{ *memtest.FakeMem }

func (m *execMem) AllRegions() []proc.Region { return m.Regions() }

func plant(t *testing.T) *execMem {
	t.Helper()
	mem := memtest.New(base, size)
	mem.Exec = []proc.Region{{Start: base, End: base + size, Executable: true}}

	// get_LocalPlayer: mov eax,[Main.player]; mov ecx,[Main.myPlayer]; tail.
	asm := append([]byte{0x8B, 0x05}, u32(playerStatic)...)
	asm = append(asm, 0x8B, 0x0D)
	asm = append(asm, u32(myPlayerStatic)...)
	asm = append(asm, localPlayerTail...)
	mem.PokeBytes(code, asm)
	mem.PokeBytes(playerStatic, u32(playerArray))
	mem.PokeI32(myPlayerStatic, 0)

	mem.PokeBytes(staticAt+layout.MainRecipeOff, u32(recipeArr))
	mem.PokeI32(recipeArr+layout.ArrLenOff, int32(len(book)))
	for i, rec := range book {
		obj := uint32(recipeObjects + i*recipeStride) //nolint:gosec // a planted address
		mem.PokeBytes(recipeArr+layout.ArrDataOff+uint32(i)*4, u32(obj))
		if rec.out == 0 && !rec.planted {
			continue // an unused slot with nothing behind it at all
		}
		made := uint32(itemObjects + i*itemStride) //nolint:gosec // a planted address
		mem.PokeBytes(obj+layout.RecipeCreateItem, u32(made))
		mem.PokeI32(made+layout.ItemType, rec.out)
		mem.PokeI32(made+layout.ItemStack, rec.stack)
		mem.PokeI32(made+layout.ItemCreateTile, rec.createTile)
		mem.PokeI32(made+layout.ItemPlaceStyle, rec.placeStyle)
		mem.PokeI32(obj+layout.RecipeRequiredTile, rec.tile)

		items := uint32(itemArrays + i*itemStride) //nolint:gosec // a planted address
		mem.PokeBytes(obj+layout.RecipeRequiredItem, u32(items))
		mem.PokeI32(items+layout.ArrLenOff, int32(len(rec.ing))) //nolint:gosec // a small count
		for j, pair := range rec.ing {
			ing := ingredientAt(i, j)
			mem.PokeBytes(items+layout.ArrDataOff+uint32(j)*4, u32(ing)) //nolint:gosec // an index
			mem.PokeI32(ing+layout.ItemType, pair[0])
			mem.PokeI32(ing+layout.ItemStack, pair[1])
		}
	}
	plantStationNames(mem)
	return &execMem{mem}
}

// ingredientAt is where one recipe's nth ingredient object goes.
func ingredientAt(recipe, n int) uint32 {
	return uint32(ingObjects + (recipe*ingPerRecipe+n)*itemStride) //nolint:gosec // a planted address
}

/*
plantStationNames writes the two instructions the statics are found through, and
everything behind them.

The lookup is a ushort per tile into the legend, and the legend holds localised
strings -- so a station name is three hops from a tile id, and every hop is a
place the walk could quietly give up and report a book with no station names in
it.
*/
func plantStationNames(mem *memtest.FakeMem) {
	tileCode := append([]byte{0x8B, 0x05}, u32(lookupStatic)...)
	tileCode = append(tileCode, 0x39, 0x70, 0x0C, 0x0F, 0x86, 0, 0, 0, 0,
		0x8D, 0x44, 0x70, 0x10, 0x0F, 0xB7, 0x00, 0x03, 0xC7)
	mem.PokeBytes(tileCodeAt, tileCode)

	legendCode := append([]byte{0x8B, 0x05}, u32(legendStatic)...)
	legendCode = append(legendCode, 0x85, 0xC0, 0x74, 0x24, 0x8B, 0x05, 0, 0, 0, 0,
		0x8B, 0x4D, 0x08, 0x39, 0x48, 0x0C, 0x0F, 0x86, 0, 0, 0, 0,
		0x8D, 0x44, 0x88, 0x10, 0x8B, 0x00)
	mem.PokeBytes(legendCodeAt, legendCode)

	mem.PokeBytes(lookupStatic, u32(lookupArr))
	mem.PokeBytes(legendStatic, u32(legendArr))

	mem.PokeI32(lookupArr+layout.ArrLenOff, 700)
	mem.PokeBytes(lookupArr+layout.ArrDataOff+benchTile*2, []byte{benchLegend, 0})

	mem.PokeI32(legendArr+layout.ArrLenOff, 64)
	mem.PokeBytes(legendArr+layout.ArrDataOff+benchLegend*4, u32(legendText))
	mem.PokeBytes(legendText+uint32(layout.LocalizedTextValue), u32(stationNameAt))
	mem.PlantMonoString(stationNameAt, benchName)
}

func u32(v uint32) []byte {
	return []byte{byte(v), byte(v >> 8), byte(v >> 16), byte(v >> 24)}
}

// localPlayerTail is the pattern the resolver looks for, pinned against the
// Python by the locate package's own tests.
var localPlayerTail = []byte{
	0x39, 0x48, 0x0C, 0x0F, 0x86, 0x07, 0x00, 0x00, 0x00,
	0x8D, 0x44, 0x88, 0x10, 0x8B, 0x00, 0xC3,
}

