var repoRoot = func() string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Dir(filepath.Dir(filepath.Dir(file)))
}()

func askPython(t *testing.T, script string, into any) {
	t.Helper()
	ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, "python3", "-c", script) //nolint:gosec // a generated fixture
	cmd.Dir = repoRoot
	out, err := cmd.CombinedOutput()
	if err != nil && strings.Contains(string(out), "ModuleNotFoundError") {
		t.Skip("the Python package is not importable here")
	}
	require.NoErrorf(t, err, "asking the Python: %s", out)
	require.NoError(t, json.Unmarshal(out, into))
}

// Both walk the same array to the same book.
func TestExtractingMatchesThePython(t *testing.T) {
	var want map[string]any
	askPython(t, pyPlant()+`
print(json.dumps(R.extract(mem)))`, &want)

	got, err := recipes.Extract(plant(t))
	require.NoError(t, err)

	blob, err := json.Marshal(struct {
		Recipes   []game.Recipe     `json:"recipes"`
		Stations  map[string]string `json:"stations"`
		TileIcons map[string][]int  `json:"tileicons"`
	}{got.Recipes, got.Stations, got.TileIcons})
	require.NoError(t, err)
	var mine map[string]any
	require.NoError(t, json.Unmarshal(blob, &mine))
	require.Equal(t, want, mine, "the two read different books")
}

/*
And the book itself is what the fixture planted.

The comparison above only says the two agree, and two walks that both stopped
after the output item agree perfectly.
*/
func TestTheBookIsWhatWasPlanted(t *testing.T) {
	got, err := recipes.Extract(plant(t))
	require.NoError(t, err)
	require.Len(t, got.Recipes, 4, "the unused slots were read as recipes")

	torch := got.Recipes[0]
	require.Equal(t, 8, torch.Out, "a different item is made")
	require.Equal(t, 3, torch.N, "a different number of them")
	require.Equal(t, [][]int{{23, 1}, {9, 1}}, torch.Ing, "different ingredients")
	require.Nil(t, torch.Tile, "something made by hand was given a station")

	sword := got.Recipes[1]
	require.NotNil(t, sword.Tile, "a recipe made at a station has none")
	require.Equal(t, 18, *sword.Tile, "a different station")

	require.Equal(t, map[string][]int{"35": {16, 2}}, got.TileIcons,
		"the tile a placeable output draws from was not recorded")

	// A recipe with no stack written makes one, not none.
	last := got.Recipes[3]
	require.Equal(t, 71, last.Out)
	require.Equal(t, 1, last.N, "a recipe with no stack was read as making nothing")
	require.Len(t, last.Ing, 40, "more ingredients were read than the game holds")

	require.Equal(t, map[string]string{"18": benchName}, got.Stations,
		"the station name was not read out of the game's own table")
}

// A game with no recipe array says so rather than returning an empty book.
func TestExtractingWithNoArray(t *testing.T) {
	mem := plant(t)
	mem.PokeBytes(staticAt+layout.MainRecipeOff, u32(0))

	_, err := recipes.Extract(mem)
	require.ErrorIs(t, err, recipes.ErrNoRecipes)
}

// An array whose length is absurd is a wrong pointer, not a book.
func TestExtractingAnImplausibleArray(t *testing.T) {
	mem := plant(t)
	mem.PokeI32(recipeArr+layout.ArrLenOff, recipes.MaxRecipes+1)

	_, err := recipes.Extract(mem)
	require.ErrorIs(t, err, recipes.ErrNoRecipes)
}

/*
Saving writes the shape the game package reads back.

The two halves are in different packages and only the file connects them, so a
field renamed on one side is a book that loads empty.
*/
func TestSavingIsReadBack(t *testing.T) {
	got, err := recipes.Extract(plant(t))
	require.NoError(t, err)

	path := filepath.Join(t.TempDir(), "recipes.json")
	require.NoError(t, recipes.Save(got, path))

	raw, err := os.ReadFile(path) //nolint:gosec // a path this test made
	require.NoError(t, err)
	var back game.Recipes
	require.NoError(t, json.Unmarshal(raw, &back))
	require.Equal(t, got.Recipes, back.Recipes, "the recipes did not survive the file")
	require.Equal(t, got.TileIcons, back.TileIcons, "the tile icons did not")
	require.NotContains(t, string(raw), ", ", "the file was written with spaces in it")
}

/*
A pattern that matches twice names nothing.

Two candidates mean the shape is no longer unique to the instruction that was
meant, and picking one would name the wrong static -- which does not fail, it
produces station names read out of unrelated memory.
*/
func TestASecondMatchGivesUpOnTheNames(t *testing.T) {
	mem := plant(t)
	got, err := recipes.Extract(mem)
	require.NoError(t, err)
	require.NotEmpty(t, got.Stations, "the fixture never named a station to begin with")

	twice := plant(t)
	tileCode := twice.Read(tileCodeAt, 24)
	twice.PokeBytes(tileCodeAt+0x1000, tileCode)

	got, err = recipes.Extract(twice)
	require.NoError(t, err)
	require.Empty(t, got.Stations, "an ambiguous pattern was resolved anyway")
	require.NotEmpty(t, got.Recipes, "the book itself was lost with the names")
}

/*
A station the lookup cannot name is left unnamed, rather than named from
whatever is at that address.

Three ways it can fail, and all three are a read that succeeds and means
nothing: a tile past the end of the lookup, a legend index past the end of the
legend, and a name that is there but empty. None of them fails visibly -- the
book comes out with a station called something out of unrelated memory.
*/
func TestStationsThatCannotBeNamed(t *testing.T) {
	const (
		pastLookup = 6000 // beyond the lookup array's length
		pastLegend = 200  // beyond the legend array's length
		emptyName  = 21   // a tile whose name is there and blank
		badText    = base + 0x33000
		emptyText  = base + 0x33100
		emptyStr   = base + 0x33200
	)

	mem := plant(t)
	// Something plausible at every address the missing guard would read.
	mem.PokeBytes(lookupArr+layout.ArrDataOff+pastLookup*2, []byte{1, 0})
	mem.PokeBytes(legendArr+layout.ArrDataOff+1*4, u32(badText))
	mem.PokeBytes(badText+uint32(layout.LocalizedTextValue), u32(stationNameAt))

	mem.PokeBytes(lookupArr+layout.ArrDataOff+emptyName*2, []byte{pastLegend, 0})
	mem.PokeBytes(legendArr+layout.ArrDataOff+pastLegend*4, u32(badText))

	mem.PokeBytes(lookupArr+layout.ArrDataOff+19*2, []byte{6, 0})
	mem.PokeBytes(legendArr+layout.ArrDataOff+6*4, u32(emptyText))
	mem.PokeBytes(emptyText+uint32(layout.LocalizedTextValue), u32(emptyStr))
	mem.PlantMonoString(emptyStr, "")

	// Three more recipes, one per way of failing.
	for i, tile := range []int32{pastLookup, emptyName, 19} {
		slot := len(book) + i
		obj := uint32(recipeObjects + slot*recipeStride)                    //nolint:gosec // a planted address
		made := uint32(itemObjects + slot*itemStride)                       //nolint:gosec // a planted address
		mem.PokeI32(recipeArr+layout.ArrLenOff, int32(slot+1))              //nolint:gosec // a small count
		mem.PokeBytes(recipeArr+layout.ArrDataOff+uint32(slot)*4, u32(obj)) //nolint:gosec // an index
		mem.PokeBytes(obj+layout.RecipeCreateItem, u32(made))
		mem.PokeI32(made+layout.ItemType, int32(500+i)) //nolint:gosec // a small index
		mem.PokeI32(made+layout.ItemStack, 1)
		mem.PokeI32(made+layout.ItemCreateTile, -1)
		mem.PokeI32(obj+layout.RecipeRequiredTile, tile)
	}

	got, err := recipes.Extract(mem)
	require.NoError(t, err)
	require.Equal(t, map[string]string{"18": benchName}, got.Stations,
		"a station was named from memory the lookup does not reach")
}
